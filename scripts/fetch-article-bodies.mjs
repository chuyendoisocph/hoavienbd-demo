// Fetch full post bodies from nirvana.com.my WP REST API and clean Divi shortcodes.
// Only fetches the slugs actually linked from src/lib/articles-content.ts.
// Output: src/lib/articles-body.ts  (Record<slug, cleaned HTML body>)
import { writeFileSync, readFileSync } from "node:fs";

// Derive the slugs we care about from the article list's hrefs.
const contentTs = readFileSync(
  new URL("../src/lib/articles-content.ts", import.meta.url),
  "utf8",
);
const EXTRA_SLUGS = ["5-main-advantages-of-pre-planning"];
const slugs = [
  ...new Set([
    ...[...contentTs.matchAll(/"href":\s*"\/([^"]+?)\/?"/g)]
      .map((m) => m[1].replace(/^\/|\/$/g, ""))
      .filter(Boolean),
    ...EXTRA_SLUGS,
  ]),
];
console.log("Slugs to fetch:", slugs.length);

const params = new URLSearchParams({ per_page: "100", _fields: "slug,title,date,content" });
for (const s of slugs) params.append("slug[]", s);
const API = "https://www.nirvana.com.my/wp-json/wp/v2/posts?" + params.toString();

function decodeEntities(s) {
  return s
    .replace(/&#8217;|&#8216;/g, "’")
    .replace(/&#8220;|&#8221;/g, '"')
    .replace(/&#8243;/g, '"')
    .replace(/&#8242;/g, "'")
    .replace(/&#8211;/g, "–")
    .replace(/&#8212;/g, "—")
    .replace(/&#8230;/g, "…")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&");
}

function clean(html) {
  let out = html;
  // Strip Divi builder shortcodes: [et_pb_...] and [/et_pb_...]
  out = out.replace(/\[\/?et_pb[^\]]*\]/g, "");
  // Strip any other leftover simple shortcodes
  out = out.replace(/\[\/?(vc_[^\]]*|caption[^\]]*)\]/g, "");
  // Remove empty paragraphs / whitespace-only paragraphs
  out = out.replace(/<p>\s*(?:&nbsp;| |\s)*<\/p>/gi, "");
  out = out.replace(/<p>\s*<\/p>/gi, "");
  // Collapse excessive newlines
  out = out.replace(/\n{2,}/g, "\n").trim();
  return out;
}

const res = await fetch(API, { headers: { "User-Agent": "Mozilla/5.0" } });
if (!res.ok) {
  console.error("Fetch failed:", res.status, res.statusText);
  process.exit(1);
}
const posts = await res.json();
console.log("Fetched", posts.length, "posts");

const bodies = {};
for (const p of posts) {
  const raw = p?.content?.rendered ?? "";
  const cleaned = decodeEntities(clean(raw));
  if (cleaned && cleaned.length > 40) {
    bodies[p.slug] = cleaned;
  } else {
    console.warn("  (skipped, empty body):", p.slug);
  }
}

const header = `/** Auto-generated by scripts/fetch-article-bodies.mjs
 * Full article bodies from nirvana.com.my (WP REST), Divi shortcodes stripped.
 * Keyed by slug. Content kept in original language (translate later).
 */

export const ARTICLE_BODIES: Record<string, string> = `;

const ts = header + JSON.stringify(bodies, null, 2) + ";\n";
writeFileSync(new URL("../src/lib/articles-body.ts", import.meta.url), ts, "utf8");
console.log("Wrote src/lib/articles-body.ts with", Object.keys(bodies).length, "bodies");
